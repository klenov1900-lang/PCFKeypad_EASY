// ============================================================
// PCFKeypad_EASY.h
// Матричная клавиатура 4x4 через I2C-расширитель PCF8574.
// Использует I2C_EASY как низкоуровневый слой TWI.
// ============================================================
// Возможности:
//   - Сканирование матрицы 4x4 (16 клавиш)
//   - Антидребезг (настраиваемый)
//   - Автоповтор (hold + repeat)
//   - Энергосбережение (сон через заданное время)
//   - Защита от ghosting
//   - Игнорирование множественного нажатия
//   - Обработка ошибок I2C
//   - Своя распиновка и раскладка
//   - Поддержка прерываний
// ============================================================
#ifndef PCF_KEYPAD_EASY_H
#define PCF_KEYPAD_EASY_H

#include <stdint.h>
#include "I2C_EASY.h"

// ============================================================
// КОНСТАНТЫ
// ============================================================
#define PCFPAD_ADDR_DEFAULT  0x20   // адрес PCF8574 по умолчанию

// Состояния клавиши (возврат из pcfpad_get_key)
#define PCFPAD_KEY_RELEASED  0      // клавиша не нажата
#define PCFPAD_KEY_PRESSED   1      // клавиша только что нажата
#define PCFPAD_KEY_HOLD      2      // клавиша удерживается (автоповтор)
#define PCFPAD_KEY_ERROR     0xFE   // ошибка I2C

// ============================================================
// ИНИЦИАЛИЗАЦИЯ
// ============================================================
// Стандартная распиновка:
//   R1-R4 = P4-P7, C1-C4 = P0-P3
//   Раскладка: A B C D / 1 2 3 4 / 5 6 7 8 / 9 0 * #
void pcfpad_init(uint8_t addr);

// Своя распиновка и раскладка
void pcfpad_init_custom(uint8_t addr,
                        const uint8_t rows[4],
                        const uint8_t cols[4],
                        const char keys[4][4]);

// ============================================================
// НАСТРОЙКА
// ============================================================
void pcfpad_set_debounce(uint16_t ms);        // default 50
void pcfpad_set_hold_delay(uint16_t ms);      // default 800
void pcfpad_set_repeat_delay(uint16_t ms);    // default 150
void pcfpad_set_scan_interval(uint16_t ms);   // default 1
void pcfpad_set_active_low(uint8_t enable);   // default 1

// ============================================================
// ЭНЕРГОСБЕРЕЖЕНИЕ
// ============================================================
void    pcfpad_set_power_save(uint8_t enable);
void    pcfpad_set_power_save_timeout(uint32_t ms);
uint8_t pcfpad_is_power_save(void);

// ============================================================
// ОПРОС
// ============================================================
uint8_t pcfpad_get_key(void);        // PCFPAD_KEY_*
char    pcfpad_get_current(void);    // текущий символ
uint8_t pcfpad_is_pressed(void);     // 0/1

// ============================================================
// ПРЕРЫВАНИЕ
// ============================================================
void    pcfpad_handle_interrupt(void);   // вызывать из ISR

// ============================================================
// ДИАГНОСТИКА
// ============================================================
uint8_t pcfpad_is_connected(void);   // 1 = отвечает
uint8_t pcfpad_get_error(void);      // код последней ошибки I2C

// ============================================================
// СЛУЖЕБНОЕ
// ============================================================
void    pcfpad_reset(void);          // сброс состояния

#endif // PCF_KEYPAD_EASY_H